#!/usr/bin/env python3
"""Extract the diagnostic questions, maturity scale and India diagnostics from the
source document (docs/source/AI readiness assessment.docx) into a generated
TypeScript module, so the application never re-types the source wording.

Usage: npm run extract:spec
"""
import json
import re
import sys
from pathlib import Path

import docx  # python-docx

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "source" / "AI readiness assessment.docx"
OUT = ROOT / "src" / "data" / "sourceSpec.generated.ts"


def clean(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace(" ", " ")).strip()


def main() -> int:
    d = docx.Document(str(SRC))
    questions = []  # {id, text, headingIndex}
    headings = []   # dimension headings in order of appearance
    summary = []    # summary table rows
    scale = []
    india = []

    # Walk the body in order so each question table can be tied to the preceding heading.
    from docx.table import Table
    from docx.text.paragraph import Paragraph

    current_heading = None
    for child in d.element.body.iterchildren():
        tag = child.tag.split("}")[1]
        if tag == "p":
            p = Paragraph(child, d)
            t = clean(p.text)
            m = re.match(r"^Dimension (\d+)\s*[—\-–]+\s*(.+)$", t)
            if m:
                current_heading = {"number": int(m.group(1)), "heading": clean(m.group(2))}
                headings.append(current_heading)
        elif tag == "tbl":
            tbl = Table(child, d)
            rows = [[clean(c.text) for c in r.cells] for r in tbl.rows]
            if not rows:
                continue
            header = [h.lower() for h in rows[0]]
            if header[:2] == ["id", "diagnostic question"]:
                for r in rows[1:]:
                    questions.append(
                        {"id": r[0], "text": r[1], "dimension": current_heading["number"]}
                    )
            elif header[:3] == ["dimension", "questions", "weight"]:
                for r in rows[1:]:
                    if r[0].lower() == "total":
                        continue
                    m = re.match(r"^(\d+)\.\s*(.+)$", r[0])
                    summary.append(
                        {
                            "number": int(m.group(1)),
                            "sourceTableName": m.group(2),
                            "questions": int(r[1]),
                            "weight": int(r[2].rstrip("%")),
                        }
                    )
            elif header[:3] == ["score", "maturity", "interpretation"]:
                for r in rows[1:]:
                    scale.append({"score": int(r[0]), "label": r[1], "description": r[2]})
            elif header[:2] == ["area", "additional diagnostic question"]:
                for r in rows[1:]:
                    india.append({"area": r[0], "question": r[1]})

    # --- sanity checks against the spec the product is built to ---
    assert len(questions) == 100, f"expected 100 questions, found {len(questions)}"
    assert len(summary) == 12, "expected 12 dimensions in the summary table"
    assert sum(s["weight"] for s in summary) == 100, "weights must total 100"
    assert sum(s["questions"] for s in summary) == 100, "question counts must total 100"
    assert len(scale) == 5, "expected 5 maturity levels"
    assert len(india) == 10, "expected 10 India-specific diagnostics"
    for s in summary:
        n = sum(1 for q in questions if q["dimension"] == s["number"])
        assert n == s["questions"], f"dimension {s['number']}: {n} questions vs {s['questions']} declared"
    assert len({q["id"] for q in questions}) == 100, "question IDs must be unique"

    heading_by_number = {h["number"]: h["heading"] for h in headings}
    for s in summary:
        s["sourceHeading"] = heading_by_number[s["number"]]

    payload = {
        "summary": summary,
        "scale": scale,
        "questions": questions,
        "india": india,
    }
    body = json.dumps(payload, indent=2, ensure_ascii=False)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// AUTO-GENERATED by scripts/extract_questions.py from\n"
        "// docs/source/AI readiness assessment.docx — do not edit by hand.\n"
        "// Re-run `npm run extract:spec` to regenerate.\n\n"
        f"export const SOURCE_SPEC = {body} as const;\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(questions)} questions, {len(summary)} dimensions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
