// six in each set. Each entry is [topic, question, DPDP reference, "not applicable" allowed].
//
// The common set is written to cover every duty in the Act and Rules that a
// Data Fiduciary meets: governance, data mapping, notice, consent, permitted
// uses, rights, grievance, children, security, breach, retention, vendors,
// cross-border transfers, Significant Data Fiduciary duties, training and
// monitoring. The reference column says which part each question checks, and a
// test fails if any of those duties has no question.
//
// Questions only ask. They never say what the law requires; the Resources page
// does that, and marks each instrument as checked or not.

